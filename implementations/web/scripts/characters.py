"""Generate SVG poses and CSS motion from the delegated Characters selection."""
import json
import re

EASING = {"EASE_OUT": "ease-out", "EASE_IN_AND_OUT": "ease-in-out"}


def matrix(node, frame):
    (a, c, x), (b, d, y) = node["absoluteTransform"]
    origin = frame["absoluteTransform"]
    return [a, b, c, d, x - origin[0][2], y - origin[1][2]]


def pose(frame, character, roles):
    body, *parts = frame["children"]
    eyes = next(layer for layer in parts if layer["name"] == "ojos")
    layers = {"body": body, "left-eye": eyes["children"][0], "right-eye": eyes["children"][1]}
    if character == "beni":
        layers["mouth"] = parts[-1]
    else:
        layers["left-shadow"] = next(layer for layer in parts if layer["name"] == "sombra L")
        layers["right-shadow"] = next(layer for layer in parts if layer["name"] == "sombra R")
    result = {}
    for name, node in layers.items():
        if len(node["paths"]) != 1 or len(node["fills"]) > 1 or node["effects"] or node["strokes"]:
            raise ValueError(f"Unsupported path anatomy for {node['id']}")
        path = node["paths"][0]
        paint = next(iter(node["fills"]), None)
        role = roles[paint["boundVariables"]["color"]["id"]] if paint else "navi/shadow"
        result[name] = {
            "id": node["id"], "d": path["data"],
            "rule": "evenodd" if path["windingRule"] == "EVENODD" else "nonzero",
            "transform": matrix(node, frame),
            "opacity": node["opacity"] * paint["opacity"] if paint and paint["visible"] and node["visible"] else 0,
            "token": "--characters-color-" + role.replace("/", "-"),
        }
    return result


def keyframes(character, part, poses, cycle):
    all_layers = [p[part] for p in poses.values()]
    if len({tuple(re.findall(r"[A-Z]", layer["d"])) for layer in all_layers}) != 1:
        raise ValueError(f"Incompatible path commands for {character}/{part}")
    fields = ("d", "transform", "opacity")
    changing = [field for field in fields if any(layer[field] != all_layers[0][field] for layer in all_layers)]
    if not changing:
        return []

    duration = sum(row["holdMs"] + row["transitionMs"] for row in cycle)
    name = f"bh-{character}-{part}"
    css = [
        f'  .bh-character[data-character="{character}"][data-playing="true"] [data-part="{part}"] {{',
        f"    animation: {name} {duration}ms linear infinite;",
        "  }", f"  @keyframes {name} {{",
    ]

    def state(time, layer, easing="linear"):
        values = {
            "d": f'path("{layer["d"]}")',
            "transform": "matrix(" + ", ".join(map(str, layer["transform"])) + ")",
            "opacity": layer["opacity"],
        }
        style = " ".join(f"{field}: {values[field]};" for field in changing)
        return f"    {100*time/duration:.10f}% {{ {style} animation-timing-function: {easing}; }}"

    elapsed = 0
    for row in cycle:
        layer = poses[row["frame"]][part]
        css.append(state(elapsed, layer))
        elapsed += row["holdMs"]
        css.append(state(elapsed, layer, EASING[row["easing"]]))
        elapsed += row["transitionMs"]
    css += [state(duration, poses[cycle[-1]["next"]][part]), "  }"]
    return css


def build(root):
    data = json.loads((root / "specs/data/characters.v1.0.0.json").read_text())
    source = json.loads((root / data["source"]).read_text())
    model = {"width": data["width"], "height": data["height"], "characters": {}}
    css = ["/* Generated by scripts/characters.py from the delegated Characters selection. */",
           "@media (prefers-reduced-motion: no-preference) {"]
    if len(data["sets"]) != len(source["sets"]):
        raise ValueError("Characters set count differs from source")
    for group, set_node in zip(data["sets"], source["sets"]):
        character = group["key"]
        cycle = group["frames"]
        if set_node["id"] != group["sourceSet"] or any(
            row["next"] != cycle[(i + 1) % len(cycle)]["frame"] for i, row in enumerate(cycle)
        ):
            raise ValueError("Unexpected Characters sequence")
        frames = {}
        if len(cycle) != len(set_node["variants"]):
            raise ValueError("Characters frame count differs from source")
        for row, frame in zip(cycle, set_node["variants"]):
            if row["source"] != frame["id"]:
                raise ValueError("Characters frame ID differs from source")
            frames[row["frame"]] = pose(frame, character, source["sourcePaintRoles"])
        order = (["body", "left-eye", "right-eye", "mouth"] if character == "beni"
                 else ["body", "left-shadow", "left-eye", "right-eye", "right-shadow"])
        model["characters"][character] = {"frames": frames, "order": order}
        for part in order:
            css.extend(keyframes(character, part, frames, cycle))
    css.append("}")
    return {"src/generated/characters.json": json.dumps(model, ensure_ascii=False, indent=2) + "\n",
            "src/generated/characters.css": "\n".join(css) + "\n"}
